/**
 * Writes the next batch of daily scrambles (docs/home-plan.md → card 2) as a
 * SQL seed for `public.daily_scrambles`.
 *
 *   node scripts/generate-daily-scrambles.mjs [first-day] [days]
 *   node scripts/generate-daily-scrambles.mjs 2026-11-25 60
 *
 * `first-day` defaults to today in IST, `days` to 60. Uses cubing.js's
 * random-state 3x3 scrambler, the same one the timer uses in the browser
 * (src/lib/timer/scrambler.ts), here in Node. The seed is idempotent
 * (`on conflict do nothing`), so a day already loaded keeps its scramble:
 * nobody's daily changes under them.
 *
 * Output: supabase/DataSeeds/<first-day as yyyymmdd>000000_daily_scrambles.sql.
 * Load it with `supabase db query --linked -f <file>` (or the SQL editor)
 * after the daily scramble migration is applied.
 */
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { randomScrambleForEvent } from "cubing/scramble";

const root = resolve(import.meta.dirname, "..");

function istToday() {
  return new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Kolkata" }).format(new Date());
}

function addDays(day, n) {
  const d = new Date(`${day}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

const first = process.argv[2] ?? istToday();
const days = Number(process.argv[3] ?? 60);
if (!/^\d{4}-\d{2}-\d{2}$/.test(first) || !Number.isInteger(days) || days < 1 || days > 366) {
  console.error("usage: node scripts/generate-daily-scrambles.mjs [yyyy-mm-dd] [days 1-366]");
  process.exit(1);
}

const rows = [];
for (let i = 0; i < days; i++) {
  const day = addDays(first, i);
  const scramble = (await randomScrambleForEvent("333")).toString();
  // Scramble notation has no quotes other than the prime, which SQL escapes by doubling.
  rows.push(`  ('${day}', '333', '${scramble.replaceAll("'", "''")}')`);
}
const last = addDays(first, days - 1);
const sql = `-- Daily scrambles ${first} to ${last} (${days} days, 3x3, random-state).
-- Generated by scripts/generate-daily-scrambles.mjs. Needs the
-- 20261125000100_daily_scramble.sql migration. Idempotent: a day already
-- loaded keeps its scramble.
insert into public.daily_scrambles (day, puzzle, scramble) values
${rows.join(",\n")}
on conflict (day) do nothing;
`;
const out = join(root, "supabase/DataSeeds", `${first.replaceAll("-", "")}000000_daily_scrambles.sql`);
writeFileSync(out, sql);
console.log(`wrote ${out} (${first} to ${last})`);
process.exit(0);
